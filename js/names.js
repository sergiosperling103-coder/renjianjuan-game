function poolKey(year) {
  const y = Math.max(1930, Math.min(2000, Math.floor(year / 10) * 10));
  return String(y);
}

function pickOne(arr, exclude) {
  const pool = arr.filter(x => !exclude.includes(x));
  if (!pool.length) return arr[Math.floor(Math.random() * arr.length)];
  return pool[Math.floor(Math.random() * pool.length)];
}

function pickGiven(gender, year, exclude) {
  const pool = gender === '女' ? GIVEN_F[poolKey(year)] : GIVEN_M[poolKey(year)];
  return pickOne(pool, exclude || []);
}

function randomSurname(exclude) {
  return pickOne(SURNAMES, exclude || []);
}

function genFullName(gender, year, surname, exclude) {
  const s = surname || randomSurname(exclude);
  return s + pickGiven(gender, year, (exclude || []).map(n => n.slice(1)));
}

function suggestNames(gender, year, count) {
  const n = count || 4;
  const out = [];
  for (let i = 0; i < n * 3 && out.length < n; i++) {
    const name = genFullName(gender, year, null, out);
    if (!out.includes(name)) out.push(name);
  }
  return out;
}

window.NameGen = { suggestNames, genFullName, pickGiven, randomSurname };
